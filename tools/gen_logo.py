#!/usr/bin/env python3
"""
Embed the app logo in the binary.

Reads assets/logo.png (the MiSTerEmby logo on a transparent background,
360px — big enough for the largest size the app draws it at) and writes
src/logo_png.h, a byte array the app decodes with stb_image at startup.
Built in rather than shipped beside the binary, so the release zip, the
in-app updater and the Downloader databases need nothing new.

Run from project root after changing the logo: python3 tools/gen_logo.py
"""

with open("assets/logo.png", "rb") as f:
    data = f.read()

lines = []
for i in range(0, len(data), 16):
    lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",")

with open("src/logo_png.h", "w") as f:
    f.write("/* Generated by tools/gen_logo.py from assets/logo.png. Do not edit. */\n")
    f.write("#ifndef LOGO_PNG_H\n#define LOGO_PNG_H\n\n")
    f.write("static const unsigned char logo_png[%d] = {\n" % len(data))
    f.write("\n".join(lines))
    f.write("\n};\n\n#endif\n")
print("src/logo_png.h: %d bytes" % len(data))
