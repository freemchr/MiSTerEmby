#!/usr/bin/env python3
"""
Embed the app logo and icon in the binary.

Reads assets/logo.png (the full MiSTerEmby logo on a transparent background,
360px — big enough for the largest size the app draws it at) and
assets/icon.png (just the logo's monitor, for the top bar and dialog
headers), and writes src/logo_png.h, byte arrays the app decodes with
stb_image on first use.
Built in rather than shipped beside the binary, so the release zip, the
in-app updater and the Downloader databases need nothing new.

Run from project root after changing the logo: python3 tools/gen_logo.py
"""

def emit(f, name, path):
    with open(path, "rb") as src:
        data = src.read()
    f.write("static const unsigned char %s[%d] = {\n" % (name, len(data)))
    for i in range(0, len(data), 16):
        f.write("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",\n")
    f.write("};\n\n")
    print("%s: %d bytes" % (name, len(data)))


with open("src/logo_png.h", "w") as f:
    f.write("/* Generated by tools/gen_logo.py from assets/logo.png and assets/icon.png.\n"
            " * Do not edit. */\n")
    f.write("#ifndef LOGO_PNG_H\n#define LOGO_PNG_H\n\n")
    emit(f, "logo_png", "assets/logo.png")
    emit(f, "icon_png", "assets/icon.png")
    f.write("#endif\n")
