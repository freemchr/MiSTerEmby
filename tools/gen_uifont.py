#!/usr/bin/env python3
"""
Build the UI display font: Fredoka SemiBold, smooth-edged, for the big text
(home tiles, screen titles, the focused title under the posters).

Reads assets/fonts/Fredoka-SemiBold.ttf (Fredoka by Milena Brandao, SIL Open
Font Licence, see assets/fonts/Fredoka-OFL.txt; instanced from the Google
Fonts variable font at wght=600) and renders every character the app's text
can contain (printable ASCII and Latin-1) with ImageMagick, at one large
size. The glyphs go side by side into one greyscale strip, coverage as
brightness, and src/uifont_data.h gets the strip as a PNG byte array plus
each glyph's x offset and advance. The app scales the strip down once per
size it draws at (see src/uifont.c).

Needs ImageMagick's convert and identify. Run from the project root:
python3 tools/gen_uifont.py
"""
import os, subprocess, tempfile

FONT = "assets/fonts/Fredoka-SemiBold.ttf"
POINTS = 48
CHARS = list(range(32, 127)) + list(range(160, 256))

tmp = tempfile.mkdtemp()
paths, widths = [], []
height = None
for cp in CHARS:
    path = os.path.join(tmp, "g%03d.png" % cp)
    # No shell is involved (argv list), but ImageMagick itself treats %, \
    # and a leading @ specially in label: text.
    c = chr(cp)
    if cp == 32:
        # A lone space is no label at all; its advance is what it adds
        # between two letters.
        def width(t):
            out = subprocess.run(["convert", "-font", FONT, "-pointsize", str(POINTS),
                                  "label:" + t, "-format", "%w %h", "info:"],
                                 capture_output=True, text=True, check=True).stdout.split()
            return int(out[0]), int(out[1])
        (w1, h), (w2, _) = width("x x"), width("xx")
        w = w1 - w2
        subprocess.run(["convert", "-size", "%dx%d" % (w, h), "xc:black",
                        "-colorspace", "gray", "-depth", "8", path], check=True)
    else:
        text = {"%": "%%", "\\": "\\\\", "@": "\\@"}.get(c, c)
        subprocess.run(["convert", "-background", "black", "-fill", "white", "-font", FONT,
                        "-pointsize", str(POINTS), "label:" + text,
                        "-colorspace", "gray", "-depth", "8", path], check=True)
        w, h = map(int, subprocess.run(["identify", "-format", "%w %h", path],
                                       capture_output=True, text=True, check=True).stdout.split())
    if height is None: height = h
    if h != height:   # same font and size: every label is one line tall
        subprocess.run(["convert", path, "-gravity", "north", "-background", "black",
                        "-extent", "%dx%d" % (w, height), path], check=True)
    paths.append(path)
    widths.append(w)

strip = os.path.join(tmp, "strip.png")
subprocess.run(["convert"] + paths + ["+append", "-colorspace", "gray", "-depth", "8",
                "-define", "png:color-type=0", "-strip", strip], check=True)
os.makedirs("assets", exist_ok=True)
with open(strip, "rb") as f:
    data = f.read()
with open("assets/uifont.png", "wb") as f:
    f.write(data)

offsets, x = [], 0
for w in widths:
    offsets.append(x); x += w

with open("src/uifont_data.h", "w") as f:
    f.write("/* Generated by tools/gen_uifont.py from assets/fonts/Fredoka-SemiBold.ttf.\n"
            " * Do not edit. Fredoka: SIL Open Font Licence, assets/fonts/Fredoka-OFL.txt. */\n")
    f.write("#ifndef UIFONT_DATA_H\n#define UIFONT_DATA_H\n\n")
    f.write("#define UIFONT_SRC_H %d   /* line height in the strip, pixels */\n" % height)
    f.write("#define UIFONT_FIRST_LATIN1 160\n")
    f.write("#define UIFONT_GLYPHS %d\n\n" % len(CHARS))
    f.write("/* Index by codepoint: 32..126 -> 0..94, 160..255 -> 95..190. */\n")
    f.write("static const unsigned short uifont_x[%d] = {%s};\n" % (len(CHARS), ",".join(map(str, offsets))))
    f.write("static const unsigned char  uifont_w[%d] = {%s};\n\n" % (len(CHARS), ",".join(map(str, widths))))
    f.write("static const unsigned char uifont_png[%d] = {\n" % len(data))
    for i in range(0, len(data), 16):
        f.write("    " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",\n")
    f.write("};\n\n#endif\n")
print("strip %dx%d, %d glyphs, %d bytes" % (x, height, len(CHARS), len(data)))
